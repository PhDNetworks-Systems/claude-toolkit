#!/usr/bin/env python3
"""Qualify both required documents without generating or changing content."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parent.parent
records=[]
for name in ['CLAUDE.md','CHANGELOG.md']:
 path=root/name
 if path.is_symlink() or not path.is_file():raise SystemExit('Missing or symlinked required document: '+name)
 data=path.read_bytes()
 if not data.strip():raise SystemExit('Empty required document: '+name)
 records.append({'path':name,'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
print(json.dumps({'passed':True,'documents':records,'autogenerated':False}))
